CREATE TABLE flashcards.decks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flashcards.cards (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deck_id INTEGER NOT NULL REFERENCES flashcards.decks(id) ON DELETE CASCADE,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flashcards.tags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ASCII case folding, without changing accents.
CREATE UNIQUE INDEX idx_tags_name_nocase ON flashcards.tags (
  translate(name, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')
);

CREATE TABLE flashcards.card_tags (
  card_id INTEGER NOT NULL REFERENCES flashcards.cards(id) ON DELETE CASCADE,
  tag_id INTEGER NOT NULL REFERENCES flashcards.tags(id) ON DELETE CASCADE,
  PRIMARY KEY (card_id, tag_id)
);

CREATE INDEX idx_cards_deck_id ON flashcards.cards(deck_id);
CREATE INDEX idx_card_tags_tag_id ON flashcards.card_tags(tag_id);
