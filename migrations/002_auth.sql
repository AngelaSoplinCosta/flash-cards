CREATE TABLE flashcards.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9_]{3,32}$'),
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flashcards.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES flashcards.users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_expiry ON flashcards.sessions(expires_at);
CREATE INDEX idx_sessions_user ON flashcards.sessions(user_id);

CREATE TABLE flashcards.auth_limits (
  key TEXT PRIMARY KEY,
  attempts INTEGER NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_auth_limits_expiry ON flashcards.auth_limits(expires_at);

-- NULL preserves the existing collection until an operator assigns it locally.
ALTER TABLE flashcards.decks ADD COLUMN user_id INTEGER REFERENCES flashcards.users(id);
ALTER TABLE flashcards.tags ADD COLUMN user_id INTEGER REFERENCES flashcards.users(id);
ALTER TABLE flashcards.decks DROP CONSTRAINT decks_name_key;
CREATE UNIQUE INDEX idx_decks_user_name ON flashcards.decks(user_id, name) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX idx_decks_legacy_name ON flashcards.decks(name) WHERE user_id IS NULL;
DROP INDEX flashcards.idx_tags_name_nocase;
CREATE UNIQUE INDEX idx_tags_user_name ON flashcards.tags(user_id,
  translate(name, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX idx_tags_legacy_name ON flashcards.tags(
  translate(name, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')) WHERE user_id IS NULL;
